  function translate(language, key, values = {}) {
    const selected = messages[language] || messages.en;
    let message = selected[key] ?? messages.en[key] ?? key;
    if (key === "taskCount") {
      const plural = values.count === 0
        ? "other"
        : new Intl.PluralRules(language in messages ? language : "en").select(values.count);
      message = selected[plural === "one" ? "taskCountOne" : "taskCountOther"]
        ?? messages.en[plural === "one" ? "taskCountOne" : "taskCountOther"];
    }
    return message.replace(/\{(\w+)\}/g, (match, name) => (
      Object.hasOwn(values, name) ? String(values[name]) : match
    ));
  }

  function applyTranslations(language) {
    document.documentElement.lang = language in messages ? language : "en";
    document.querySelectorAll("[data-i18n]").forEach((element) => {
      element.textContent = translate(language, element.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
      element.setAttribute("placeholder", translate(language, element.dataset.i18nPlaceholder));
    });
    document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
      element.setAttribute("aria-label", translate(language, element.dataset.i18nAriaLabel));
    });
    document.querySelectorAll("[data-i18n-title]").forEach((element) => {
      element.setAttribute("title", translate(language, element.dataset.i18nTitle));
    });
  }

  window.EnnoicI18n = { supportedLanguages: Object.keys(messages), translate, applyTranslations };
